"""Pydantic schemas for the Phase 3 Threat Detection Engine."""

from datetime import datetime
from enum import Enum
from typing import Any
from pydantic import BaseModel, ConfigDict, Field


class SeverityLevel(str, Enum):
    """Normalized security threat severity levels."""

    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"


class DetectionType(str, Enum):
    """Categorical classification of detection rules."""

    UNUSUAL_PORT = "UNUSUAL_PORT"
    PORT_SCAN = "PORT_SCAN"
    SUSPICIOUS_PROCESS = "SUSPICIOUS_PROCESS"
    BURST_ACTIVITY = "BURST_ACTIVITY"
    UNEXPECTED_LISTENER = "UNEXPECTED_LISTENER"
    REPEATED_ATTEMPTS = "REPEATED_ATTEMPTS"


class SecurityEventSchema(BaseModel):
    """Structured security threat event generated by the detection engine."""

    id: str = Field(..., description="Unique event identifier (e.g. sec-1a2b3c4d)")
    timestamp: str = Field(..., description="ISO 8601 UTC timestamp of detection")
    rule_id: str = Field(..., description="Identifier of the rule that generated this event")
    rule_name: str = Field(..., description="Human-readable rule name")
    detection_type: str = Field(..., description="Category code of detection")
    severity: SeverityLevel = Field(..., description="Severity classification (low, medium, high)")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Confidence score from 0.0 to 1.0")
    title: str = Field(..., description="Short summary of the detected threat")
    description: str = Field(..., description="Clear explanation of why this was flagged")
    source_ip: str | None = Field(default=None, description="Local or source IP address")
    source_port: int | None = Field(default=None, description="Local or source port")
    dest_ip: str | None = Field(default=None, description="Destination or remote IP address")
    dest_port: int | None = Field(default=None, description="Destination or remote port")
    protocol: str | None = Field(default=None, description="Transport protocol (TCP/UDP)")
    process_name: str | None = Field(default=None, description="Associated executable name")
    pid: int | None = Field(default=None, description="Process ID")
    evidence: dict[str, Any] = Field(default_factory=dict, description="Detailed evidence payload")
    recommendations: list[str] = Field(default_factory=list, description="Recommended SOC triage steps")

    model_config = ConfigDict(from_attributes=True)


class SecurityEventListResponse(BaseModel):
    """Paginated or filtered list response for security events."""

    total: int
    items: list[SecurityEventSchema]
    high_count: int
    medium_count: int
    low_count: int
    limit: int
    offset: int

    model_config = ConfigDict(from_attributes=True)


class DetectionRuleSchema(BaseModel):
    """Schema representing an inspectable and configurable detection rule."""

    id: str
    name: str
    description: str
    category: str
    severity: SeverityLevel
    enabled: bool
    config: dict[str, Any] = Field(default_factory=dict)

    model_config = ConfigDict(from_attributes=True)


class DetectionRuleToggleRequest(BaseModel):
    """Request payload to toggle or update a detection rule."""

    enabled: bool


class SecuritySummaryResponse(BaseModel):
    """High-level summary of security posture and recent threat detections."""

    total_events: int
    high_severity_count: int
    medium_severity_count: int
    low_severity_count: int
    active_rules_count: int
    total_rules_count: int
    last_scan_time: str | None
    threat_level: str  # LOW, ELEVATED, HIGH, CRITICAL
    top_flagged_processes: list[dict[str, Any]]
    top_flagged_ports: list[dict[str, Any]]

    model_config = ConfigDict(from_attributes=True)


class ManualScanResponse(BaseModel):
    """Response returned upon triggering a manual security scan."""

    scanned_connections_count: int
    new_threats_detected: int
    total_active_threats: int
    events: list[SecurityEventSchema]
    scan_duration_ms: float
    timestamp: str

    model_config = ConfigDict(from_attributes=True)
